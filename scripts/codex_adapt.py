#!/usr/bin/env python3
"""codex_adapt.py — translate the Claude-format harness into Codex's formats.

Skills need no translation (Codex reads the same SKILL.md from .agents/skills).
Two things do:

  agents <agents-dir> <out-dir>
      Each agents/*.md (YAML-ish frontmatter + Markdown body) becomes
      <out-dir>/<name>.toml with name, description, developer_instructions.
      Codex custom agents have no `tools:` allowlist, so the contract is
      restated in the instructions and read-only roles get sandbox_mode.
      Stale generated files (those carrying GENERATED_MARK) are removed.

  mcp <mcp.json> <config.toml>
      Rewrites the project's .mcp.json servers as [mcp_servers.*] tables in a
      marker-delimited block of .codex/config.toml. Everything outside the block
      is left alone; an empty/missing .mcp.json removes the block.

Standard library only (no TOML writer exists in it, so strings are emitted by hand).
"""
import json
import os
import re
import sys

GENERATED_MARK = "# Generated by agent-framework scripts/codex_adapt.py"
BLOCK_START = "# >>> sdd-harness mcp (generated from .mcp.json; do not edit) >>>"
BLOCK_END = "# <<< sdd-harness mcp <<<"
READ_ONLY_ROLES = {"reviewer", "auditor"}

PREAMBLE = """\
You are running under Codex. This agent definition was written for Claude Code, so:
- Tool names below (Read, Write, Edit, Bash, Grep, Glob, Agent) mean your equivalents: read files, apply patches, run shell commands, search, and spawn a subagent by name.
- Codex cannot enforce a per-agent tool allowlist. The "Tool contract" section is binding on you anyway; do not use a capability it forbids.
- `${CLAUDE_PLUGIN_ROOT}` and `.claude/` paths refer to files in this repository's `.claude/` directory.
"""


def toml_str(s):
    return json.dumps(s, ensure_ascii=False)  # JSON basic strings are valid TOML


def toml_multiline(s):
    if "'''" not in s and not s.endswith("'"):
        return "'''\n" + s.rstrip("\n") + "\n'''"
    return toml_str(s)


def parse_frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if not m:
        raise ValueError("no frontmatter")
    fields, key = {}, None
    for line in m.group(1).split("\n"):
        kv = re.match(r"([A-Za-z_-]+):\s*(.*)$", line)
        if kv and not line.startswith(" "):
            key = kv.group(1)
            val = kv.group(2).strip()
            fields[key] = "" if val in (">", "|") else val
        elif key and line.strip():
            fields[key] = (fields[key] + " " + line.strip()).strip()
    return fields, m.group(2).lstrip("\n")


def tools_of(fields):
    raw = fields.get("tools", "").strip()
    if raw.startswith("["):
        raw = raw[1:-1]
    return [t.strip() for t in raw.split(",") if t.strip()]


def convert_agent(path):
    with open(path, encoding="utf-8") as fh:
        content = fh.read()
    fields, body = parse_frontmatter(content)
    name, role = fields["name"], fields.get("role", "")
    tools = tools_of(fields)
    contract = [f"## Tool contract (role: {role or 'unspecified'})", "",
                "Declared tools: " + (", ".join(tools) or "none") + "."]
    if role in READ_ONLY_ROLES:
        contract.append("You are read-only with respect to the product: never write, edit or commit files.")
    if role == "verifier":
        contract.append("Do not write or edit product files. Do not read source files: judge the running system by its observable behaviour only.")
    out = [GENERATED_MARK + f" from agents/{os.path.basename(path)}. Edit that file instead.",
           f"name = {toml_str(name)}",
           f"description = {toml_str(fields['description'])}"]
    if role in READ_ONLY_ROLES:
        out.append('sandbox_mode = "read-only"')
    instructions = PREAMBLE + "\n" + "\n".join(contract) + "\n\n" + body
    out.append("developer_instructions = " + toml_multiline(instructions))
    return name, "\n".join(out) + "\n"


def cmd_agents(src, dest):
    os.makedirs(dest, exist_ok=True)
    written = set()
    for fn in sorted(os.listdir(src)):
        if not fn.endswith(".md"):
            continue
        name, toml = convert_agent(os.path.join(src, fn))
        with open(os.path.join(dest, name + ".toml"), "w", encoding="utf-8") as fh:
            fh.write(toml)
        written.add(name + ".toml")
    for fn in os.listdir(dest):
        p = os.path.join(dest, fn)
        if fn.endswith(".toml") and fn not in written:
            with open(p, encoding="utf-8") as fh:
                is_generated = fh.readline().startswith(GENERATED_MARK)
            if is_generated:
                os.remove(p)
    print(f"  Wrote {len(written)} Codex agents to {dest}")


ENV_REF = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)(?::-[^}]*)?\}")


def server_table(name, cfg):
    key = name if re.fullmatch(r"[A-Za-z0-9_-]+", name) else toml_str(name)
    lines, notes = [f"[mcp_servers.{key}]"], []
    if "url" in cfg:
        lines.append(f"url = {toml_str(cfg['url'])}")
        static, from_env = {}, {}
        for h, v in (cfg.get("headers") or {}).items():
            if not isinstance(v, str):
                static[h] = v
                continue
            bearer = re.fullmatch(r"Bearer \$\{([A-Za-z_][A-Za-z0-9_]*)\}", v)
            whole = ENV_REF.fullmatch(v)
            if h.lower() == "authorization" and bearer:
                lines.append(f"bearer_token_env_var = {toml_str(bearer.group(1))}")
            elif whole:
                from_env[h] = whole.group(1)
            else:
                static[h] = v
        if static:
            lines.append("http_headers = { " + ", ".join(f"{toml_str(k)} = {toml_str(v)}" for k, v in static.items()) + " }")
        if from_env:
            lines.append("env_http_headers = { " + ", ".join(f"{toml_str(k)} = {toml_str(v)}" for k, v in from_env.items()) + " }")
    else:
        lines.append(f"command = {toml_str(cfg['command'])}")
        if cfg.get("args"):
            lines.append("args = [" + ", ".join(toml_str(a) for a in cfg["args"]) + "]")
        static, forward = {}, []
        for k, v in (cfg.get("env") or {}).items():
            if not isinstance(v, str):
                static[k] = v
                continue
            whole = ENV_REF.fullmatch(v)
            if whole and whole.group(1) == k:
                forward.append(k)
            elif ENV_REF.search(v):
                notes.append(f"env {k} uses interpolation Codex does not expand; set it in your shell and forward it")
                forward.append(k)
            else:
                static[k] = v
        if static:
            lines.append("env = { " + ", ".join(f"{toml_str(k)} = {toml_str(v)}" for k, v in static.items()) + " }")
        if forward:
            lines.append("env_vars = [" + ", ".join(toml_str(k) for k in forward) + "]")
    return "\n".join(lines), notes


def cmd_mcp(mcp_path, config_path):
    servers = {}
    if os.path.exists(mcp_path):
        with open(mcp_path, encoding="utf-8") as fh:
            servers = json.load(fh).get("mcpServers", {})
    existing = ""
    if os.path.exists(config_path):
        with open(config_path, encoding="utf-8") as fh:
            existing = fh.read()
    block_re = re.compile(re.escape(BLOCK_START) + r".*?" + re.escape(BLOCK_END) + r"\n?", re.S)
    rest = block_re.sub("", existing).rstrip("\n")
    if not servers:
        if existing and rest != existing.rstrip("\n"):
            if rest:
                with open(config_path, "w", encoding="utf-8") as fh:
                    fh.write(rest + "\n")
            else:
                os.remove(config_path)
            print(f"  Removed generated MCP block from {config_path}")
        return
    tables, warnings = [], []
    for name, cfg in sorted(servers.items()):
        t, notes = server_table(name, cfg)
        tables.append(t)
        warnings += [f"{name}: {n}" for n in notes]
    block = BLOCK_START + "\n" + "\n\n".join(tables) + "\n" + BLOCK_END + "\n"
    os.makedirs(os.path.dirname(config_path) or ".", exist_ok=True)
    with open(config_path, "w", encoding="utf-8") as fh:
        fh.write((rest + "\n\n" if rest else "") + block)
    print(f"  Wrote {len(servers)} MCP server(s) from .mcp.json to {config_path}")
    for w in warnings:
        print(f"  Warning: {w}", file=sys.stderr)


def main(argv):
    if len(argv) == 4 and argv[1] == "agents":
        cmd_agents(argv[2], argv[3])
    elif len(argv) == 4 and argv[1] == "mcp":
        cmd_mcp(argv[2], argv[3])
    else:
        print(__doc__, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
