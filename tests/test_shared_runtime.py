"""Verify the shared harness layout in disposable consumer checkouts."""
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


class SharedRuntimeTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="shared runtime ")
        self.addCleanup(self.tmp.cleanup)
        self.target = Path(self.tmp.name) / "consumer"
        self.target.mkdir()
        # The shell installer invokes python3; use the interpreter running this suite.
        binary = Path(self.tmp.name) / "bin"
        binary.mkdir()
        (binary / "python3").symlink_to(sys.executable)
        self.env = dict(os.environ, PATH=str(binary) + os.pathsep + os.environ["PATH"])

    def install(self, *flags):
        result = subprocess.run(["bash", str(ROOT / "scripts/install-skills.sh"),
                                 "--harness", "claude,codex", *flags, str(self.target)],
                                env=self.env, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        return result

    def test_fresh_install_has_shared_skills_roles_and_agent_routing(self):
        self.install()
        self.assertEqual((self.target / ".agents/skills").readlink(), Path("../.claude/skills"))
        self.assertFalse((self.target / ".codex/agents").exists())
        self.assertIn("$ship", (self.target / "AGENTS.md").read_text())
        self.assertIn(".claude/agents/", (self.target / "AGENTS.md").read_text())
        for name, role in {"ship": "architect", "architect": "architect", "spec": "planner",
                           "plan": "planner", "tasks": "planner", "implement": "executor",
                           "critique": "critic", "qa": "tester", "qa-explore": "qa-engineer",
                           "publish": "publisher",
                           "audit": "archivist"}.items():
            instructions = (self.target / f".agents/skills/{name}/SKILL.md").read_text()
            self.assertIn(f".claude/agents/{role}.md", instructions, name)
            self.assertIn("Read", instructions, name)
            self.assertIn("in full", instructions, name)
        # Discovery must expose edits to the canonical file immediately, without regeneration.
        canonical = self.target / ".claude/skills/ship/SKILL.md"
        canonical.write_text(canonical.read_text() + "\nLocal instruction\n")
        self.assertIn("Local instruction", (self.target / ".agents/skills/ship/SKILL.md").read_text())
        self.install()
        self.assertIn("Local instruction", canonical.read_text())
        self.assertFalse((self.target / ".codex/agents").exists())

    def test_install_preserves_canonical_model_catalog_and_resolution_contract(self):
        self.install()
        for source in (ROOT / "plugins/sdd/agents").glob("*.md"):
            installed = self.target / ".claude/agents" / source.name
            self.assertEqual(installed.read_text().split("---", 2)[1],
                             source.read_text().split("---", 2)[1], source.name)
        dispatch = (self.target / ".agents/skills/ship/SKILL.md").read_text()
        self.assertIn("provider_defaults", dispatch)
        self.assertIn("omit the Codex model override", dispatch)
        catalog = self.target / ".claude/sdd/model-tiers.json"
        source_catalog = ROOT / "plugins/sdd/config/model-tiers.json"
        self.assertEqual(catalog.read_bytes(), source_catalog.read_bytes())
        self.assertIn(".claude/sdd/model-tiers.json", dispatch)
        data = json.loads(catalog.read_text())
        data["workhorse"]["openai"] = "local-supported-model"
        catalog.write_text(json.dumps(data))
        self.install()
        self.assertEqual(json.loads(catalog.read_text()), data)

    def test_existing_project_rules_hooks_and_codex_files_survive(self):
        existing = {
            "AGENTS.md": "# Project rules\nDo not replace this file.\n",
            ".claude/sdd/config.json": '{"commands":{"test":"custom test"}}\n',
            ".codex/agents/custom.toml": 'name="custom"\n',
            ".codex/agents/legacy.toml": '# Generated by agent-framework scripts/codex_adapt.py\nname="legacy"\n',
        }
        for relative, content in existing.items():
            path = self.target / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        settings = self.target / ".claude/settings.json"
        settings.write_text(json.dumps({"permissions": {"deny": ["Read(.env)"]},
            "hooks": {"PreToolUse": [{"hooks": [{"type": "command", "command": "guard-secret"}]}]},
            "enabledPlugins": {"sdd@sdd-harness": True, "other@tools": True}}))
        first = self.install()
        self.install()
        for relative, content in existing.items():
            self.assertEqual((self.target / relative).read_text(), content, relative)
        data = json.loads(settings.read_text())
        self.assertEqual(data["permissions"]["deny"], ["Read(.env)"])
        self.assertEqual(data["hooks"]["PreToolUse"][0]["hooks"][0]["command"], "guard-secret")
        self.assertEqual(len(data["hooks"]["SessionStart"]), 1)
        self.assertTrue(data["enabledPlugins"]["sdd@sdd-harness"])
        self.assertTrue(data["enabledPlugins"]["other@tools"])
        self.assertIn("plugin", first.stderr.lower())
        self.assertIn("legacy", first.stderr.lower())

    def test_foreign_discovery_symlink_and_directory_are_preserved(self):
        agents = self.target / ".agents"
        agents.mkdir()
        link = agents / "skills"
        link.symlink_to("../custom-skills", target_is_directory=True)
        self.install()
        self.assertEqual(link.readlink(), Path("../custom-skills"))
        link.unlink()
        link.mkdir()
        (link / "mine").write_text("keep")
        self.install()
        self.assertEqual((link / "mine").read_text(), "keep")

    def test_unresolved_incoming_files_survive_reruns_and_retired_edits_stay_tracked(self):
        self.install()
        ship = self.target / ".claude/skills/ship/SKILL.md"
        ship.write_text(ship.read_text() + "\nCustom rule\n")
        manifest = self.target / ".claude/sdd/.harness-manifest"
        data = json.loads(manifest.read_text())
        data["files"]["skills/ship/SKILL.md"] = "0" * 64
        retired = self.target / ".claude/agents/retired.md"
        retired.write_text("edited retired role\n")
        data["files"]["agents/retired.md"] = "0" * 64
        manifest.write_text(json.dumps(data))
        self.install()
        incoming = self.target / ".claude/sdd/upstream/skills/ship/SKILL.md"
        expected = incoming.read_bytes()
        self.install()
        self.assertTrue(incoming.exists())
        self.assertEqual(incoming.read_bytes(), expected)
        self.assertTrue(retired.exists())
        self.install("--overwrite-local")
        self.assertFalse(retired.exists())
        self.assertFalse(incoming.exists())


if __name__ == "__main__":
    unittest.main()
